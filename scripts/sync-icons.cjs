'use strict'
/**
 * Splice official provider brand marks into the hand-written client bundles.
 *
 * Source: @lobehub/icons-static-svg (MIT) — the canonical SVG collection for AI
 * and LLM brands. Using each vendor's own mark to identify that vendor in a
 * picker is nominative use and is what every comparable client does; it is not
 * the same as adopting someone's mark as our own product identity.
 *
 * We inline rather than import because the client bundles are hand-written in the
 * harness's module-table format and have no bundler to resolve a dependency. The
 * generated region is regenerated by running this script, so the icons stay
 * traceable to their upstream version instead of being pasted in by hand.
 *
 *   node scripts/sync-icons.cjs          rewrite the generated regions
 *   node scripts/sync-icons.cjs --check  fail if they are stale (CI-friendly)
 *
 * The monochrome variants are chosen deliberately: they carry fill="currentColor",
 * so every mark inherits one text colour and the set reads as a coherent system
 * instead of a row of clashing brand palettes.
 */

const fs = require('node:fs')
const path = require('node:path')

/** provider route id -> icon basename in the upstream collection. */
const ICONS = {
  'openai-codex': 'openai',
  xai: 'grok',
  openrouter: 'openrouter',
  'kimi-coding': 'kimi',
  deepseek: 'deepseek',
}

const BEGIN = '// BEGIN GENERATED provider-icons (scripts/sync-icons.cjs) — do not edit'
const END = '// END GENERATED provider-icons'

const TARGETS = [
  'plugins/client-ui-accounts/lib/client.js',
]

// Model makers as well as routing providers. A model served by OpenRouter
// should show its maker's mark whenever that identity is known.
const MODEL_ICONS = Object.fromEntries((
  'openai grok openrouter kimi deepseek anthropic claude google gemini gemma meta '
  + 'mistral qwen zai zhipu cohere moonshot minimax bytedance tencent hunyuan nvidia '
  + 'microsoft ibm inception liquid poolside upstage longcat kwaipilot baidu '
  + 'alibaba ai21 ai2 aionlabs arcee nousresearch deepcogito perplexity together '
  + 'fireworks groq cerebras sambanova deepinfra huggingface ollama lmstudio '
  + 'bedrock azure vertexai cloudflare novita nebius siliconcloud stepfun '
  + 'internlm yi baichuan inflection dbrx snowflake xiaomimimo vllm'
).split(' ').map(name => [name, name]))

function iconsDir () {
  const manifest = require.resolve('@lobehub/icons-static-svg/package.json')
  return path.join(path.dirname(manifest), 'icons')
}

function upstreamVersion () {
  return require('@lobehub/icons-static-svg/package.json').version
}

/**
 * Take just the drawable children of the SVG.
 *
 * The wrapper carries `height="1em"`, an inline `style`, and a `<title>`; we drop
 * all three because the consumer sets its own size and supplies its own
 * accessible name, and a stray <title> would surface as a tooltip.
 */
function extractBody (file) {
  const raw = fs.readFileSync(file, 'utf8')
  const open = raw.indexOf('>')
  const close = raw.lastIndexOf('</svg>')
  if (open === -1 || close === -1) throw new Error(`unrecognised SVG: ${file}`)
  return raw
    .slice(open + 1, close)
    .replace(/<title>.*?<\/title>/gs, '')
    .trim()
}

/** Does the wrapper declare fill="currentColor"? Colour variants do not. */
function usesCurrentColor (file) {
  return /<svg[^>]*fill="currentColor"/.test(fs.readFileSync(file, 'utf8'))
}

function buildRegion (icons = ICONS) {
  const dir = iconsDir()
  const lines = [
    BEGIN,
    `    // @lobehub/icons-static-svg@${upstreamVersion()} (MIT). Regenerate: node scripts/sync-icons.cjs`,
    '    const PROVIDER_ICONS = {',
  ]
  for (const [provider, name] of Object.entries(icons)) {
    const file = path.join(dir, `${name}.svg`)
    if (!fs.existsSync(file)) throw new Error(`missing upstream icon: ${name}.svg`)
    if (!usesCurrentColor(file)) throw new Error(`${name}.svg is not a currentColor variant`)
    lines.push(`      ${JSON.stringify(provider)}: ${JSON.stringify(extractBody(file))},`)
  }
  lines.push('    };')
  lines.push(`    ${END.trim()}`)
  // The caller splices this in place of BEGIN..END, so the first line carries no
  // indentation (it inherits the position BEGIN already had) and the rest do.
  return lines.join('\n').replace(/\n    \/\/ END/, '\n    // END')
}

function apply (target, region, check) {
  const file = path.join(__dirname, '..', target)
  const source = fs.readFileSync(file, 'utf8')
  const start = source.indexOf(BEGIN)
  const stop = source.indexOf(END)
  if (start === -1 || stop === -1) throw new Error(`no generated region in ${target}`)

  // Keep whatever indentation the region already sits at, so the splice does not
  // reformat the surrounding file.
  const before = source.slice(0, start)
  const after = source.slice(stop + END.length)
  const output = before + region + after

  if (check) {
    if (output !== source) {
      console.error(`stale generated icons in ${target} — run: node scripts/sync-icons.cjs`)
      process.exitCode = 1
    }
    return
  }
  fs.writeFileSync(file, output)
  console.log(output === source ? `unchanged ${target}` : `updated ${target}`)
}

const check = process.argv.includes('--check')
const region = buildRegion()
for (const target of TARGETS) apply(target, region, check)
apply('plugins/client-ui-theme-holo/lib/client.js', buildRegion(MODEL_ICONS), check)
