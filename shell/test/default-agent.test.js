'use strict'
const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { ensureDefaultAgent, GUIDANCE } = require('../src/default-agent.cjs')
const anchor = path.resolve(__dirname, '..')

test('managed agent retains the exact shipped tool composition and access policy', t => {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'dsh-agent-test-'))
  t.after(() => fs.rmSync(home, { recursive: true, force: true }))
  const dir = path.join(home, 'bundle')
  fs.mkdirSync(dir)
  ensureDefaultAgent(home, anchor, dir)
  const file = path.join(dir, 'agent.patch.yml')
  const generated = fs.readFileSync(file, 'utf8')
  const pkg = require.resolve('@deepseek-ai/dsh/package.json', { paths: [anchor] })
  const source = fs.readFileSync(require.resolve('@deepseek-ai/dsh-web-app/presets/standard.patch.yml', { paths: [path.dirname(pkg)] }), 'utf8')
  const rows = text => text.split('\n').filter(line => /^          - id:|^            name:|^            disabled:/.test(line))
  assert.deepEqual(rows(generated), rows(source))
  assert.ok(generated.includes(JSON.stringify(GUIDANCE)))
  assert.match(GUIDANCE, /current access policy/)
  assert.match(GUIDANCE, /not proof of a working game/)
  ensureDefaultAgent(home, anchor, dir)
  assert.equal(fs.readFileSync(file, 'utf8'), generated)
  assert.equal(fs.statSync(file).mode & 0o777, 0o600)
})

test('an existing custom preset is never overwritten', t => {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'dsh-agent-test-'))
  t.after(() => fs.rmSync(home, { recursive: true, force: true }))
  const dir = path.join(home, '.agent-presets', 'dsh-agent')
  fs.mkdirSync(dir, { recursive: true })
  fs.writeFileSync(path.join(dir, 'agent.cordis.yml'), 'custom')
  assert.throws(() => ensureDefaultAgent(home, anchor), /left untouched/)
  assert.equal(fs.readFileSync(path.join(dir, 'agent.cordis.yml'), 'utf8'), 'custom')
})
